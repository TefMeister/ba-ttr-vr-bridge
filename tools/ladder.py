#!/usr/bin/env python3
"""ladder.py -- build one test rung as its own MO2 profile, and check it before a launch.

A rung switches mods ON and OFF; it never reorders. Everything that is on keeps the Begin Again author's order (the
order of the base profile's modlist.txt and loadorder.txt). Before every launch `check` proves that no active plugin is
missing a master and that every master loads before the plugin that needs it.

    python ladder.py make  --mo2 <Begin Again folder> --name "rung-00 flat base" --enable <mod> [<mod> ...]
                           [--base "Begin Again"] [--files-from "Debug Mode (Base TTW and req mods)"]
                           [--inis vanilla|base] [--windowed] [--mute-music]
    python ladder.py check --mo2 <Begin Again folder> --name "rung-00 flat base"

--inis vanilla   the game's own INIs, as the New Vegas launcher wrote them (Documents/My Games/FalloutNV)
--inis base      the INIs of the --files-from profile (the list author's)
"""
import argparse
import os
import shutil
import stat
import struct
import sys

PLUGIN_EXT = (".esm", ".esp")
INI_NAMES = ("fallout.ini", "falloutprefs.ini", "falloutcustom.ini", "custom.ini", "initweaks.ini")


def read_lines(path):
    with open(path, encoding="utf-8-sig") as f:
        return [l.rstrip("\r\n") for l in f]


def write_lines(path, lines, header=True):
    with open(path, "w", encoding="utf-8", newline="\r\n") as f:
        if header:
            f.write("# This file was automatically generated by Mod Organizer.\n")
        for l in lines:
            f.write(l + "\n")


def plugin_masters(path):
    """The masters named in a plugin's TES4 header (MAST subrecords), in order. None if unreadable."""
    try:
        with open(path, "rb") as f:
            hdr = f.read(24)
            if len(hdr) < 24 or hdr[:4] != b"TES4":
                return None
            size = struct.unpack("<I", hdr[4:8])[0]
            data = f.read(size)
    except OSError:
        return None
    out, i = [], 0
    while i + 6 <= len(data):
        typ, ln = data[i:i + 4], struct.unpack("<H", data[i + 4:i + 6])[0]
        val = data[i + 6:i + 6 + ln]
        if typ == b"MAST":
            out.append(val.rstrip(b"\x00").decode("latin-1"))
        i += 6 + ln
    return out


def mod_plugins(mods_dir, mod):
    root = os.path.join(mods_dir, mod)
    try:
        return [x for x in os.listdir(root) if x.lower().endswith(PLUGIN_EXT)]
    except OSError:
        return []


def profile_dir(mo2, name):
    return os.path.join(mo2, "profiles", name)


def make(a):
    base = profile_dir(a.mo2, a.base)
    files_from = profile_dir(a.mo2, a.files_from or a.base)
    dst = profile_dir(a.mo2, a.name)
    if os.path.exists(dst):
        sys.exit(f"profile already exists: {a.name} (remove it in MO2 first, or pick another name)")
    want = set(a.enable)
    order = read_lines(os.path.join(base, "modlist.txt"))
    names = [l[1:] for l in order if l and l[0] in "+-*"]
    missing = sorted(want - set(names))
    if missing:
        sys.exit("not in the base profile's mod list: " + ", ".join(missing))
    os.makedirs(dst)
    # everything but MO2's dated backups and the lists we write ourselves
    for x in os.listdir(files_from):
        if any(x.startswith(p + ".") and x != p for p in ("plugins.txt", "loadorder.txt", "lockedorder.txt")):
            continue
        if x in ("modlist.txt", "plugins.txt", "loadorder.txt", "lockedorder.txt"):
            continue
        s = os.path.join(files_from, x)
        if os.path.isfile(s):
            shutil.copy2(s, os.path.join(dst, x))
            os.chmod(os.path.join(dst, x), stat.S_IWRITE | stat.S_IREAD)   # copies keep a read-only flag otherwise
    new = []
    for l in order:
        if not l or l.startswith("#"):
            new.append(l)
            continue
        flag, nm = l[0], l[1:]
        if nm.endswith("_separator") or flag == "*":
            new.append(l)
        else:
            new.append(("+" if nm in want else "-") + nm)
    write_lines(os.path.join(dst, "modlist.txt"), [l for l in new if l and not l.startswith("#")])
    # plugins: those the enabled mods carry, in the base load order
    mods_dir = os.path.join(a.mo2, "mods")
    have = {}
    for m in want:
        for p in mod_plugins(mods_dir, m):
            have[p.lower()] = p
    base_lo = [l for l in read_lines(os.path.join(base, "loadorder.txt")) if l and not l.startswith("#")]
    lo = [p for p in base_lo if p.lower() in have]
    lo += sorted(p for k, p in have.items() if k not in {x.lower() for x in lo})   # any the base never listed
    write_lines(os.path.join(dst, "loadorder.txt"), lo)
    write_lines(os.path.join(dst, "plugins.txt"), lo)
    write_lines(os.path.join(dst, "lockedorder.txt"), [])
    if a.inis == "vanilla":
        mg = os.path.join(os.path.expanduser("~"), "Documents", "My Games", "FalloutNV")
        for x in INI_NAMES:
            p = os.path.join(dst, x)
            if os.path.exists(p):
                os.remove(p)
        for src, d in (("Fallout.ini", "fallout.ini"), ("FalloutPrefs.ini", "falloutprefs.ini")):
            shutil.copy2(os.path.join(mg, src), os.path.join(dst, d))
            os.chmod(os.path.join(dst, d), stat.S_IWRITE | stat.S_IREAD)
        open(os.path.join(dst, "falloutcustom.ini"), "w").close()
    edits = {}
    if a.windowed:
        edits.update({"bFull Screen": "0", "iSize W": "1280", "iSize H": "720"})
    if a.mute_music:
        edits.update({"fDefaultMusicVolume": "0.0000", "fMainMenuMusicVolume": "0.0"})
    for x in ("fallout.ini", "falloutprefs.ini", "falloutcustom.ini"):
        p = os.path.join(dst, x)
        if edits and os.path.exists(p):
            lines = read_lines(p)
            lines = [(k + "=" + edits[k]) if (k := l.split("=", 1)[0]) in edits and "=" in l else l for l in lines]
            write_lines(p, lines, header=False)
    print(f"made profile '{a.name}': {len(want)} mods on, {len(lo)} plugins, INIs {a.inis}"
          + (", windowed 1280x720" if a.windowed else "") + (", music muted" if a.mute_music else ""))
    return check_profile(a.mo2, a.name)


def check_profile(mo2, name):
    dst = profile_dir(mo2, name)
    mods_dir = os.path.join(mo2, "mods")
    on = [l[1:] for l in read_lines(os.path.join(dst, "modlist.txt")) if l.startswith("+") and not l.endswith("_separator")]
    where = {}
    for m in reversed(on):   # lowest priority first, so the winning copy is kept
        for p in mod_plugins(mods_dir, m):
            where[p.lower()] = os.path.join(mods_dir, m, p)
    active = [l for l in read_lines(os.path.join(dst, "plugins.txt")) if l and not l.startswith("#")]
    pos = {p.lower(): i for i, p in enumerate(active)}
    problems = 0
    for i, p in enumerate(active):
        path = where.get(p.lower())
        if path is None:
            print(f"  MISSING FILE: {p} is active but no enabled mod carries it"); problems += 1; continue
        ms = plugin_masters(path)
        if ms is None:
            print(f"  UNREADABLE: {p}"); problems += 1; continue
        for m in ms:
            j = pos.get(m.lower())
            if j is None:
                print(f"  MISSING MASTER: {p} needs {m}"); problems += 1
            elif j > i:
                print(f"  ORDER: {p} loads before its master {m}"); problems += 1
    print(f"check '{name}': {len(on)} mods on, {len(active)} plugins active, "
          + ("all masters present and in order" if problems == 0 else f"{problems} PROBLEM(S): do not launch"))
    return 1 if problems else 0


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    m = sub.add_parser("make")
    m.add_argument("--mo2", required=True); m.add_argument("--name", required=True)
    m.add_argument("--enable", nargs="+", required=True)
    m.add_argument("--base", default="Begin Again"); m.add_argument("--files-from")
    m.add_argument("--inis", choices=("vanilla", "base"), default="base")
    m.add_argument("--windowed", action="store_true"); m.add_argument("--mute-music", action="store_true")
    c = sub.add_parser("check")
    c.add_argument("--mo2", required=True); c.add_argument("--name", required=True)
    a = ap.parse_args()
    return make(a) if a.cmd == "make" else check_profile(a.mo2, a.name)


if __name__ == "__main__":
    sys.exit(main())
